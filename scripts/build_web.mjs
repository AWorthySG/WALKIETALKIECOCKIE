import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { assertCompleteModule } from './check_bundle.mjs';
await mkdir('dist', { recursive: true });
await build({ entryPoints: ['web/app.js'], bundle: true, format: 'esm', minify: true, target: ['safari16.4', 'chrome110'], outfile: 'dist/app.js', legalComments: 'eof' });
const files = { '/': ['web/index.html','text/html; charset=utf-8'], '/app.css': ['web/app.css','text/css; charset=utf-8'], '/app.js': ['dist/app.js','text/javascript; charset=utf-8'], '/manifest.webmanifest': ['web/manifest.webmanifest','application/manifest+json'], '/sw.js': ['web/sw.js','text/javascript; charset=utf-8'], '/icon.svg': ['web/icon.svg','image/svg+xml'] };
files['/sticker.webp'] = ['web/sticker.webp', 'image/webp'];
files['/apple-touch-icon.png'] = ['web/apple-touch-icon.png', 'image/png'];
files['/icon-maskable.png'] = ['web/icon-maskable.png', 'image/png'];
for (const size of [192, 512]) files[`/icon-${size}.png`] = [`web/icon-${size}.png`, 'image/png'];
for (const weight of [400, 600, 700, 800, 900]) files[`/fonts/nunito-${weight}.woff2`] = [`web/fonts/nunito-${weight}.woff2`, 'font/woff2'];
// Text-only files are small enough to bundle with the existing API Worker.
// This keeps the release deployable using either Wrangler or multipart API upload.
const entries = [];
for (const [url, [path, type]] of Object.entries(files)) {
  const bytes = await readFile(path), binary = type === 'image/png' || type === 'image/webp' || type === 'font/woff2';
  entries.push(`${JSON.stringify(url)}:{type:${JSON.stringify(type)},body:${binary ? `Uint8Array.from(atob(${JSON.stringify(bytes.toString('base64'))}),c=>c.charCodeAt(0))` : JSON.stringify(bytes.toString())}}`);
}
await writeFile('cloudflare/assets.js', `// Generated by npm run build.\nexport const assets = {${entries.join(',\n')}};\n`);
await build({ entryPoints: ['cloudflare/worker.js'], bundle: true, format: 'esm', platform: 'browser', target: 'es2022', outfile: 'dist/worker.js', minify: false });
// Refuse to produce a deployable Worker if either bundle is incomplete.
assertCompleteModule(await readFile('dist/app.js', 'utf8'), 'dist/app.js');
assertCompleteModule(await readFile('dist/worker.js', 'utf8'), 'dist/worker.js');
console.log('Built browser client and deployment Worker.');
